//! Types of `GET /api/v1/tls`: the certificate the daemon serves, and how to pair with it.
//!
//! A client that can't verify the daemon's certificate through a CA (a self-signed
//! certificate on a LAN) pins its public key instead. The user reads the pairing code off
//! the daemon (its startup log, or this endpoint seen through a trusted page such as
//! `https://localhost`) and compares it with the code the client computes from the
//! certificate it was actually presented. The code is the first 100 bits of
//! [`TlsCertificate::spki_sha256`] in RFC 4648 base32, in groups of four characters.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct TlsStatus {
    /// Whether this listener serves HTTPS itself (not through a reverse proxy).
    pub enabled: bool,
    /// The certificate being served. `None` while ACME is still getting the first one.
    pub certificate: Option<TlsCertificate>,
    /// ACME progress, when ACME is in use.
    pub acme: Option<AcmeState>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub enum TlsCertificateSource {
    /// Files the operator provides.
    Provided,
    /// Generated by the daemon; trusted by pairing. Its key persists, so the code is stable.
    SelfSigned,
    /// Issued by an ACME CA. Its key changes on every renewal, so don't pin it.
    Acme,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct TlsCertificate {
    pub source: TlsCertificateSource,
    /// SHA-256 of the leaf certificate's DER `SubjectPublicKeyInfo`, lowercase hex.
    pub spki_sha256: String,
    /// The short code to compare when pairing, such as `ABCD-EFGH-IJKL-MNOP-QRST`.
    pub pairing_code: String,
    #[ts(type = "number")]
    pub not_before_ms: i64,
    #[ts(type = "number")]
    pub not_after_ms: i64,
    pub dns_names: Vec<String>,
    pub ip_addresses: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct AcmeState {
    pub domains: Vec<String>,
    pub directory_url: String,
    #[ts(type = "number | null")]
    pub next_attempt_ms: Option<i64>,
    #[ts(type = "number | null")]
    pub last_issued_ms: Option<i64>,
    pub last_error: Option<String>,
    pub consecutive_failures: u32,
}
