//! The current certificate, swapped atomically, and the SNI resolver rustls asks for it.

use std::collections::HashMap;
use std::fmt;
use std::sync::{Arc, Mutex, RwLock};

use rustls::server::{ClientHello, ResolvesServerCert, ServerConfig};
use rustls::sign::CertifiedKey;
use serde::Serialize;
use tokio::sync::watch;

use crate::cert::{CertInfo, LoadedCert};
use crate::{TlsError, provider};

/// The ALPN protocol of an ACME TLS-ALPN-01 validation (RFC 8737).
pub const ACME_TLS_ALPN: &[u8] = b"acme-tls/1";

/// Where the current certificate came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum CertSource {
    /// Files the operator provides (`--tls-cert`, `--tls-key`).
    Provided,
    /// Generated by the daemon for LAN use with pinning.
    SelfSigned,
    /// Issued over ACME.
    Acme,
}

/// The certificate being served.
#[derive(Debug)]
pub struct ActiveCert {
    pub key: Arc<CertifiedKey>,
    pub info: CertInfo,
    pub source: CertSource,
}

/// The server's certificates. Cheap to clone; clones share state.
#[derive(Clone)]
pub struct CertStore {
    inner: Arc<Inner>,
}

struct Inner {
    current: RwLock<Option<Arc<ActiveCert>>>,
    /// TLS-ALPN-01 challenge certificates by (lowercase) host name.
    alpn: Mutex<HashMap<String, Arc<CertifiedKey>>>,
    /// HTTP-01 key authorizations by token.
    http01: Mutex<HashMap<String, String>>,
    /// Bumped on every certificate change.
    changed: watch::Sender<u64>,
}

impl fmt::Debug for CertStore {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("CertStore")
            .field(
                "current",
                &self.current().map(|c| (c.source, c.info.clone())),
            )
            .finish_non_exhaustive()
    }
}

impl Default for CertStore {
    fn default() -> Self {
        Self::new()
    }
}

impl CertStore {
    pub fn new() -> Self {
        Self {
            inner: Arc::new(Inner {
                current: RwLock::new(None),
                alpn: Mutex::new(HashMap::new()),
                http01: Mutex::new(HashMap::new()),
                changed: watch::channel(0).0,
            }),
        }
    }

    /// Serve `cert` from the next handshake on. Connections already open keep theirs.
    pub fn install(&self, cert: LoadedCert, source: CertSource) {
        let active = Arc::new(ActiveCert {
            key: cert.key,
            info: cert.info,
            source,
        });
        *self.inner.current.write().expect("cert lock") = Some(active);
        self.inner.changed.send_modify(|n| *n += 1);
    }

    /// The certificate being served, if there is one yet (ACME may still be issuing it).
    pub fn current(&self) -> Option<Arc<ActiveCert>> {
        self.inner.current.read().expect("cert lock").clone()
    }

    /// Notified whenever the certificate changes.
    pub fn subscribe(&self) -> watch::Receiver<u64> {
        self.inner.changed.subscribe()
    }

    /// A rustls server configuration backed by this store: TLS 1.2 and 1.3, ALPN `h2` and
    /// `http/1.1` (plus `acme-tls/1`, which only ACME validators offer), session tickets,
    /// and no 0-RTT data.
    pub fn server_config(&self) -> Result<Arc<ServerConfig>, TlsError> {
        let mut config = ServerConfig::builder_with_provider(provider())
            .with_safe_default_protocol_versions()?
            .with_no_client_auth()
            .with_cert_resolver(Arc::new(Resolver(self.clone())));
        config.alpn_protocols = vec![b"h2".to_vec(), b"http/1.1".to_vec(), ACME_TLS_ALPN.to_vec()];
        config.ticketer = rustls::crypto::ring::Ticketer::new()?;
        Ok(Arc::new(config))
    }

    /// The HTTP-01 response for `token`, while a challenge for it is pending.
    pub fn http01_response(&self, token: &str) -> Option<String> {
        self.inner.http01.lock().expect("lock").get(token).cloned()
    }

    pub(crate) fn set_http01(&self, token: &str, key_authorization: &str) {
        self.inner
            .http01
            .lock()
            .expect("lock")
            .insert(token.to_owned(), key_authorization.to_owned());
    }

    pub(crate) fn remove_http01(&self, token: &str) {
        self.inner.http01.lock().expect("lock").remove(token);
    }

    pub(crate) fn set_alpn_challenge(&self, host: &str, cert: Arc<CertifiedKey>) {
        self.inner
            .alpn
            .lock()
            .expect("lock")
            .insert(host.to_ascii_lowercase(), cert);
    }

    pub(crate) fn remove_alpn_challenge(&self, host: &str) {
        self.inner
            .alpn
            .lock()
            .expect("lock")
            .remove(&host.to_ascii_lowercase());
    }
}

struct Resolver(CertStore);

impl fmt::Debug for Resolver {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("Resolver")
    }
}

impl ResolvesServerCert for Resolver {
    fn resolve(&self, hello: ClientHello<'_>) -> Option<Arc<CertifiedKey>> {
        // RFC 8737: a validator offers only `acme-tls/1` and gets the challenge certificate
        // for the name it asks for. Nobody else ever gets a challenge certificate.
        let acme = hello
            .alpn()
            .is_some_and(|mut protocols| protocols.any(|p| p == ACME_TLS_ALPN));
        if acme {
            let name = hello.server_name()?.to_ascii_lowercase();
            return self.0.inner.alpn.lock().expect("lock").get(&name).cloned();
        }
        self.0.current().map(|c| c.key.clone())
    }
}
